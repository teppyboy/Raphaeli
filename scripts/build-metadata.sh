#!/bin/bash
# Emit source-derived target/build metadata for the kernel and linked kext bundle.
set -e
X=${GPU_SRC_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}
TARGET=""
HEADER=""
PRINT=0
while [ "$#" -gt 0 ]; do
    case "$1" in
        --target) shift; [ "$#" -gt 0 ] || { echo "build-metadata.sh: --target requires sequoia or tahoe" >&2; exit 1; }; TARGET=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]') ;;
        --target=*) TARGET=$(printf '%s' "${1#--target=}" | tr '[:upper:]' '[:lower:]') ;;
        --header) shift; [ "$#" -gt 0 ] || { echo "build-metadata.sh: --header requires a path" >&2; exit 1; }; HEADER=$1 ;;
        --print-version) PRINT=1 ;;
        --help|-h) echo "usage: scripts/build-metadata.sh --target sequoia|tahoe [--header path] [--print-version]"; exit 0 ;;
        *) echo "build-metadata.sh: unknown option $1" >&2; exit 1 ;;
    esac
    shift
done
case "$TARGET" in
    sequoia) ;;
    tahoe)
        "$X/scripts/target-preflight.sh" tahoe "$X/Raphaeli/Kernel/Accel/upstream/SOURCE.lock" || {
            echo "build-metadata.sh: refusing unvalidated Tahoe metadata" >&2
            exit 1
        }
        ;;
    *) echo "build-metadata.sh: unsupported target '$TARGET'" >&2; exit 1 ;;
esac
commit=$(git -C "$X" rev-parse --short=12 HEAD 2>/dev/null) || {
    echo "build-metadata.sh: source revision unavailable" >&2
    exit 1
}
version="${TARGET}/${commit}"
[ "$PRINT" -eq 0 ] || printf '%s\n' "$version"
if [ -n "$HEADER" ]; then
    mkdir -p "$(dirname "$HEADER")"
    {
        echo '/* generated by scripts/build-metadata.sh; do not edit */'
        printf '#define NMX_BUILD_TARGET "%s"\n' "$TARGET"
        printf '#define NMX_BUILD_VERSION "%s"\n' "$version"
    } > "$HEADER"
fi
