#!/usr/bin/env python3
"""Prepare the pinned IOAcceleratorFamily2 headers for one target build.

The reconstructed private headers are source inputs, not an active SDK.  Keep
those inputs tracked, verify their lock file, then stage a clean include tree.
Tahoe forwarding is derived deterministically from the pinned upstream
forwarding source.  The pinned source is macOS 26.7.1; the audited target is
26.6.2 (25G83), so Tahoe remains intentionally refused until that audit is
closed.
"""
from __future__ import print_function

import argparse
import hashlib
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE_ROOT = os.path.join(ROOT, "Raphaeli", "Kernel", "Accel", "upstream")
APPROVED_METADATA = {
    "repository": "https://github.com/nullmoth/nvidia-macos-driver.git",
    "commit": "637282334617d27bccf8aa2448497c0f19465dc8",
    "source_path": "kexts/NVRM/accel",
}

RENAME = (
    ("NVResource", "RaphaeliResource"),
    ("NVSysMemory", "RaphaeliSysMemory"),
    ("NVVidMemory", "RaphaeliVidMemory"),
    ("NVSurface", "RaphaeliSurface"),
    ("NVDisplayPipe", "RaphaeliDisplayPipe"),
    ("NVGLContext", "RaphaeliGLContext"),
    ("NV2DContext", "Raphaeli2DContext"),
    ("NVCLContext", "RaphaeliCLContext"),
    ("NVVideoContext", "RaphaeliVideoContext"),
    ("NVEventMachine", "RaphaeliEventMachine"),
    ("NVDisplayMachine", "RaphaeliDisplayMachine"),
    ("NVTask", "RaphaeliTask"),
    ("NVMemoryMap", "RaphaeliMemoryMap"),
    ("NVAccel", "RaphaeliAccel"),
)


def die(message):
    print("prepare-accel-sources.py: " + message, file=sys.stderr)
    return 1


def lock_entries():
    lock = os.path.join(SOURCE_ROOT, "SOURCE.lock")
    entries = {}
    metadata = {}
    try:
        lines = open(lock).read().splitlines()
    except IOError as exc:
        raise ValueError("cannot read %s: %s" % (lock, exc))
    for line in lines:
        if not line or "=" not in line:
            continue
        name, value = line.split("=", 1)
        if name in ("repository", "commit", "source_path", "tahoe_forwarding_provenance", "target_audit", "tahoe_target_validated"):
            metadata[name] = value
        else:
            entries[name] = value
    return metadata, entries


def verify_source():
    metadata, entries = lock_entries()
    for key in ("repository", "commit", "source_path", "tahoe_forwarding_provenance", "target_audit", "tahoe_target_validated"):
        if not metadata.get(key):
            raise ValueError("SOURCE.lock missing %s" % key)
    for key, expected in APPROVED_METADATA.items():
        if metadata[key] != expected:
            raise ValueError("SOURCE.lock %s is not approved" % key)
    for rel, expected in sorted(entries.items()):
        path = os.path.join(SOURCE_ROOT, rel)
        if not os.path.isfile(path):
            raise ValueError("SOURCE.lock input missing: %s" % rel)
        actual = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if actual != expected:
            raise ValueError("SOURCE.lock hash mismatch: %s" % rel)
    return metadata, entries


def generated_forwarding(source):
    text = open(source).read()
    if not text.startswith("// GENERATED by gen_tahoe_fwd.py"):
        raise ValueError("unexpected Tahoe forwarding source banner")
    for old, new in RENAME:
        text = text.replace(old, new)
    return ("// GENERATED by prepare-accel-sources.py from pinned upstream "
            "Tahoe forwarding source. Do not edit.\n" +
            text.split("\n", 1)[1])


def prepare(target, output, check_only=False):
    metadata, entries = verify_source()
    if target == "tahoe" and metadata["tahoe_target_validated"] != "yes":
        raise ValueError(
            "refusing Tahoe: pinned forwarding provenance is %s, target audit is %s, "
            "and SOURCE.lock marks the target ABI unvalidated" %
            (metadata["tahoe_forwarding_provenance"], metadata["target_audit"]))
    if check_only:
        print("validated %s accelerator source provenance" % target)
        return
    if os.path.exists(output):
        shutil.rmtree(output)
    if not os.path.isdir(output):
        os.makedirs(output)
    for rel in sorted(entries):
        destination = os.path.join(output, rel)
        if rel == "tahoe_fwd.h":
            continue
        parent = os.path.dirname(destination)
        if not os.path.isdir(parent):
            os.makedirs(parent)
        shutil.copyfile(os.path.join(SOURCE_ROOT, rel), destination)
    generated = generated_forwarding(os.path.join(SOURCE_ROOT, "tahoe_fwd.h"))
    with open(os.path.join(output, "nmx_accel_tahoe_forwarding.h"), "w") as handle:
        handle.write(generated)
    with open(os.path.join(output, "PROVENANCE"), "w") as handle:
        handle.write("repository=%s\ncommit=%s\nsource_path=%s\n" %
                     (metadata["repository"], metadata["commit"], metadata["source_path"]))
        handle.write("tahoe_forwarding_provenance=%s\ntarget_audit=%s\n" %
                     (metadata["tahoe_forwarding_provenance"], metadata["target_audit"]))
    print("prepared %s accelerator headers in %s" % (target, output))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", choices=("sequoia", "tahoe"), required=True)
    parser.add_argument("--output", required=False)
    parser.add_argument("--check-only", action="store_true")
    args = parser.parse_args()
    if not args.check_only and not args.output:
        parser.error("--output is required unless --check-only is used")
    try:
        prepare(args.target, os.path.abspath(args.output) if args.output else "", args.check_only)
    except (IOError, OSError, ValueError) as exc:
        return die(str(exc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
